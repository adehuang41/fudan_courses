"""Task-text to canonical CALVIN task id mapping.

The mapping is generated by the Step4 task text audit. Raw dataset task ids are
not treated as authoritative; callers map from task text to a canonical task
name and then to a stable 34-way id.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path


DEFAULT_TASK_TEXT_VOCAB = Path("/home/dechao/cv_final_pj2/results/tables/step4/task_text_canonical_vocab.json")


@dataclass(frozen=True)
class TaskTextMapper:
    vocab_path: Path
    canonical_tasks: tuple[str, ...]
    task_to_id: dict[str, int]
    training_text_to_canonical: dict[str, str]
    closed_loop_goal_text_to_canonical: dict[str, str]
    validation_auto_lang_text_to_canonical: dict[str, str]

    @classmethod
    def from_json(cls, path: Path = DEFAULT_TASK_TEXT_VOCAB) -> "TaskTextMapper":
        path = Path(path)
        data = json.loads(path.read_text(encoding="utf-8"))
        return cls(
            vocab_path=path,
            canonical_tasks=tuple(str(item) for item in data["canonical_tasks"]),
            task_to_id={str(key): int(value) for key, value in data["task_to_id"].items()},
            training_text_to_canonical={
                str(key): str(value) for key, value in data["training_text_to_canonical"].items()
            },
            closed_loop_goal_text_to_canonical={
                str(key): str(value) for key, value in data["closed_loop_goal_text_to_canonical"].items()
            },
            validation_auto_lang_text_to_canonical={
                str(key): str(value) for key, value in data["validation_auto_lang_text_to_canonical"].items()
            },
        )

    @property
    def num_tasks(self) -> int:
        return len(self.canonical_tasks)

    def canonical_for_training_text(self, text: str) -> str:
        try:
            return self.training_text_to_canonical[text]
        except KeyError as exc:
            raise KeyError(f"Training task text is not in canonical task vocab: {text!r}") from exc

    def id_for_training_text(self, text: str) -> int:
        canonical = self.canonical_for_training_text(text)
        try:
            return self.task_to_id[canonical]
        except KeyError as exc:
            raise KeyError(f"Canonical task has no stable id: {canonical!r}") from exc

    def canonical_for_goal_text(self, text: str) -> str:
        try:
            return self.closed_loop_goal_text_to_canonical[text]
        except KeyError as exc:
            raise KeyError(f"Closed-loop goal text is not in canonical task vocab: {text!r}") from exc

    def id_for_goal_text(self, text: str) -> int:
        canonical = self.canonical_for_goal_text(text)
        try:
            return self.task_to_id[canonical]
        except KeyError as exc:
            raise KeyError(f"Canonical task has no stable id: {canonical!r}") from exc
